  function element(tag,className,text) {
    const node=document.createElement(tag);
    if(className) node.className=className;
    if(text!==undefined) node.textContent=text;
    return node;
  }
  function questionCard(block,index) {
    const item=element('li','disposition-question');
    const number=element('span','disposition-question-number',String(index+1).padStart(2,'0'));
    number.setAttribute('aria-hidden','true');
    const body=element('div','disposition-question-body');
    body.append(element('p','disposition-question-text',block.text));
    const button=element('button','app-question-copy','질문 복사');
    button.type='button';
    button.setAttribute('aria-label','기본성향 질문 '+(index+1)+' 복사');
    const status=element('p','disposition-question-status');
    status.setAttribute('aria-live','polite');
    const manual=element('textarea','app-question-manual');
    manual.hidden=true;manual.readOnly=true;manual.rows=7;
    manual.setAttribute('aria-label','기본성향 질문 '+(index+1)+' 직접 복사');
    button.addEventListener('click',async()=>{
      button.disabled=true;
      try {
        await navigator.clipboard.writeText(block.text);
        manual.hidden=true;
        status.textContent='질문을 복사했습니다. ChatGPT에 기본성향 결과 PDF를 첨부하고 질문을 붙여넣으세요.';
      } catch {
        manual.value=block.text;manual.hidden=false;manual.focus();manual.select();
        status.textContent='아래 질문을 직접 복사하여 기본성향 결과 PDF와 함께 사용하세요.';
      } finally {button.disabled=false;}
    });
    body.append(button,status,manual);item.append(number,body);return item;
  }
  function appendTable(host,block) {
    const table=element('table','disposition-table');
    table.setAttribute('aria-label','정신·현실·잠재의 세 측면');
    const head=element('thead'),body=element('tbody');
    block.rows.forEach((row,index)=>{
      const line=element('tr');
      row.forEach((text,column)=>{
        const heading=index===0||column===0;
        const cell=element(heading?'th':'td','',text);
        if(heading) cell.scope=index===0?'col':'row';
        line.append(cell);
      });
      (index===0?head:body).append(line);
    });
    table.append(head,body);host.append(table);
  }
